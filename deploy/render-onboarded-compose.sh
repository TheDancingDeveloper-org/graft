#!/usr/bin/env bash
# Render Compose services declared by onboard-repo.sh. Existing hand-written
# services remain in compose.yml; rows marked generated live in this overlay.
set -euo pipefail

here=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
registry=${GRAFT_MIRRORS_FILE:-$here/mirrors.tsv}
output=${1:-$here/compose.onboarded.yml}
tmp=$output.new

{
  printf '%s\n' '# Generated by deploy/render-onboarded-compose.sh from deploy/mirrors.tsv.'
  printf '%s\n' '# Do not edit this file by hand; run deploy/onboard-repo.sh.'
  printf 'services:'
  generated=0
  while IFS='|' read -r service repo _owner_repo _base token config port source; do
    [[ -n $service && $service != \#* ]] || continue
    [[ $source == generated ]] || continue
    generated=1
    env_name=${service#graft-mirror-}
    env_name=$(printf '%s' "$env_name" | tr '[:lower:]-' '[:upper:]_')
    cat <<YAML

  $service:
    image: \${GRAFT_IMAGE:?set GRAFT_IMAGE (compose --env-file deploy/image.env)}
    user: "10001:10001"
    read_only: true
    init: true
    restart: unless-stopped
    stop_grace_period: 30s
    tmpfs: [/tmp:rw,noexec,nosuid,size=64m]
    security_opt: [no-new-privileges:true]
    cap_drop: [ALL]
    networks: [graft-dev]
    container_name: graft-dev-${service#graft-}
    hostname: graft-dev-${service#graft-}
    depends_on:
      graft-server:
        condition: service_healthy
    environment:
      GRAFT_DEPLOY_CONFIG_HASH: \${GRAFT_CONFIG_HASH:-}
    command: ["graft-mirror", "follow", "--config", "/etc/graft/deploy/mirror.toml"]
    ports:
      - "\${GRAFT_BIND_IP:-127.0.0.1}:\${GRAFT_MIRROR_${env_name}_METRICS_PORT:-$port}:9465"
    volumes:
      - ./$config:/etc/graft/deploy/mirror.toml:ro
      - type: bind
        source: \${GRAFT_SECRETS_DIR:-/etc/graft}/$token
        target: /run/secrets/graft-mirror-token
        read_only: true
        bind:
          create_host_path: false
      - graft-dev-mirror-$repo:/var/lib/graft/mirror
    healthcheck:
      test: [CMD, bash, -c, "exec 3<>/dev/tcp/127.0.0.1/9465 && printf 'GET /metrics HTTP/1.1\\r\\nHost: localhost\\r\\nConnection: close\\r\\n\\r\\n' >&3 && head -n1 <&3 | grep -q ' 200 '"]
      interval: 15s
      timeout: 5s
      retries: 3
      start_period: 20s
YAML
  done <"$registry"
  [[ $generated == 1 ]] || printf ' {}\n'
  printf 'volumes:'
  generated=0
  while IFS='|' read -r service repo _owner_repo _base _token _config _port source; do
    [[ -n $service && $service != \#* ]] || continue
    [[ $source == generated ]] || continue
    generated=1
    printf '\n  graft-dev-mirror-%s:\n    name: graft-dev-mirror-%s\n' "$repo" "$repo"
  done <"$registry"
  [[ $generated == 1 ]] || printf ' {}\n'
} >"$tmp"
mv "$tmp" "$output"
